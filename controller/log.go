// calcSuccessRate 计算成功率百分比，保留 2 位小数；无调用时返回 0。
func calcSuccessRate(success, errorCount int64) float64 {
	total := success + errorCount
	if total == 0 {
		return 0
	}
	return math.Round(float64(success)/float64(total)*10000) / 100
}

// buildSuccessRateData 组装成功率响应：total 为汇总，models 为按模型明细（按调用量降序）。
func buildSuccessRateData(stats []*model.SuccessRateStatistic) gin.H {
	models := make([]gin.H, 0, len(stats))
	var totalSuccess, totalError int64
	for _, stat := range stats {
		totalSuccess += stat.SuccessCount
		totalError += stat.ErrorCount
		models = append(models, gin.H{
			"model_name":    stat.ModelName,
			"success_count": stat.SuccessCount,
			"error_count":   stat.ErrorCount,
			"success_rate":  calcSuccessRate(stat.SuccessCount, stat.ErrorCount),
		})
	}
	return gin.H{
		"total": gin.H{
			"model_name":    "",
			"success_count": totalSuccess,
			"error_count":   totalError,
			"success_rate":  calcSuccessRate(totalSuccess, totalError),
		},
		"models": models,
	}
}

